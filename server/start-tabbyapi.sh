#!/usr/bin/env bash
# Start a locally installed TabbyAPI (github.com/theroyallab/tabbyAPI, ExLlamaV3) on turboderp's EXL3 quant of
# Qwen3.8-Flash-Next. NVIDIA only. Stock weights only: no abliterated EXL3 exists (docs/ENGINES.md#tabbyapi).
# Folder: $TABBYAPI_DIR, else ~/coding/tabbyAPI, ~/tabbyAPI, ~/src/tabbyAPI. One big engine at a time: stop
# Strata/halogen/gufo first (the wizard does that for you).
#   --print-dir   the checkout
#   --print-run   the model folder when TabbyAPI and the quant are both installed, empty otherwise
# knobs (all optional):
#   TABBY_QUANT         EXL3 revision (default 3.05bpw_h5_ng5, the one with a published single-GPU guide)
#   TABBY_CTX           context tokens, multiple of 256 (default 131072)
#   TABBY_CPU_EXPERTS   experts per MoE layer (of 512) computed on the CPU from system RAM; derived from VRAM below
#   TABBY_CPU_THREADS   CPU threads for those experts (default 3/4 of the logical cores)
#   TABBY_RESERVE_MB    VRAM left free for the desktop (default 3072; 1000 flickered the screen in the guide)
# The generated config.yml is ours only while its first line says so; edit it and delete that line to keep it.
set -u
for d in "${TABBYAPI_DIR:-}" "$HOME/coding/tabbyAPI" "$HOME/tabbyAPI" "$HOME/src/tabbyAPI"; do
  [ -n "$d" ] && [ -f "$d/main.py" ] && [ -f "$d/config_sample.yml" ] && { DIR=$d; break; }
done
[ "${1:-}" = --print-dir ] && { echo "${DIR:-}"; exit 0; }
QUANT="${TABBY_QUANT:-3.05bpw_h5_ng5}"
NAME="qwen3.8-flash-next-exl3-${QUANT%%_*}"  # the folder name is the model id pi sees
if [ "${1:-}" = --print-run ]; then
  [ -n "${DIR:-}" ] && [ -x "$DIR/.venv/bin/python" ] && [ -f "$DIR/models/$NAME/config.json" ] && echo "$DIR/models/$NAME"
  exit 0
fi
[ -n "${DIR:-}" ] || { echo "TabbyAPI not found (looked in \$TABBYAPI_DIR, ~/coding/tabbyAPI, ~/tabbyAPI, ~/src/tabbyAPI): install it with scripts/install-tabbyapi.sh (or ./setup.sh, which offers it)" >&2; exit 1; }
[ -f "$DIR/models/$NAME/config.json" ] || { echo "EXL3 quant missing: $DIR/models/$NAME - scripts/install-tabbyapi.sh downloads it" >&2; exit 1; }
command -v nvidia-smi >/dev/null || { echo "no NVIDIA GPU found (nvidia-smi missing): TabbyAPI/ExLlamaV3 needs CUDA" >&2; exit 1; }

# MiB -> GB rounded: a "24 GB" card reports 24564 MiB, a "16 GB" one 16376
VRAM_GB=$(( ($(nvidia-smi --query-gpu=memory.total --format=csv,noheader,nounits | head -1 | tr -dc '0-9') + 512) / 1024 ))
RAM_GB=$(awk '/MemTotal/{printf "%d", $2/1048576}' /proc/meminfo)
# shortcut: experts-on-CPU per VRAM size is extrapolated from the one measured point in the single-GPU guide
# (400 of 512 on a 32 GB card with 64 GB RAM); nothing here has run on 24 GB. If the load runs out of VRAM, raise
# TABBY_CPU_EXPERTS (each +10 frees about 1 GB of VRAM and costs about 1 GB of RAM); replace this with a measurement.
if   [ "$VRAM_GB" -ge 30 ]; then EXPERTS=400
elif [ "$VRAM_GB" -ge 22 ]; then EXPERTS=440
elif [ "$VRAM_GB" -ge 16 ]; then EXPERTS=480
else EXPERTS=512; fi
EXPERTS="${TABBY_CPU_EXPERTS:-$EXPERTS}"
THREADS="${TABBY_CPU_THREADS:-$(( $(nproc) * 3 / 4 ))}"
CTX="${TABBY_CTX:-131072}"
RESERVE="${TABBY_RESERVE_MB:-3072}"
echo "tabbyapi: ${VRAM_GB} GB VRAM, ${RAM_GB} GB RAM -> $EXPERTS of 512 experts per layer on the CPU ($THREADS threads), ctx $CTX"
[ "$RAM_GB" -lt 56 ] && echo "  ! under ~64 GB RAM the expert arena spills into swap and decode drops from ~50 to ~2 t/s (guide measurement)" >&2

CFG="$DIR/config.yml"
MARK="# generated by qwen38-strix-halo-harness server/start-tabbyapi.sh"
if [ ! -f "$CFG" ] || [ "$(head -1 "$CFG")" = "$MARK" ]; then
  mkdir -p "$DIR/sampler_overrides"
  # fallbacks for clients that send no sampler values: bare temperature 1.0 drifts into other languages (guide)
  cat > "$DIR/sampler_overrides/qwen3_8_flash_next.yml" <<'EOF'
temperature: {override: 0.7, force: false}
top_k: {override: 20, force: false}
top_p: {override: 0.95, force: false}
min_p: {override: 0.0, force: false}
EOF
  cat > "$CFG" <<EOF
$MARK
network:
  host: 127.0.0.1
  port: 5000
  disable_auth: true   # loopback only; turn auth back on before binding anything else
model:
  model_dir: models
  model_name: $NAME
  backend: exllamav3
  max_seq_len: $CTX
  cache_size: $CTX
  cache_mode: Q8
  gpu_split_auto: true
  autosplit_reserve: [$RESERVE]
  cpu_moe_split_experts: $EXPERTS
  cpu_moe_threads: $THREADS
  ngram_ram: false
  reasoning: true
draft_model:
  draft_mode: mtp
  draft_num_tokens: 4
  dynamic_draft: true
sampling:
  override_preset: qwen3_8_flash_next
EOF
else
  echo "  using your own $CFG (no '$MARK' on its first line)" >&2
fi
cd "$DIR" || exit 1
exec "$DIR/.venv/bin/python" main.py
